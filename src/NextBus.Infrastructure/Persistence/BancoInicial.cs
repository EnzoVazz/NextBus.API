using System.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using NextBus.Application.Interfaces;

namespace NextBus.Infrastructure.Persistence;

public static class BancoInicial
{
    public static async Task GarantirAsync(IServiceProvider services)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<NextBusDb>();
        var senhas = scope.ServiceProvider.GetRequiredService<ISenhaHasher>();
        var guardadas = scope.ServiceProvider.GetRequiredService<ISenhaRepository>();

        await GarantirTabelasAsync(db);
        await GarantirSenhaAsync(db, senhas, guardadas, "marina.costa@email.com", "Marina#2026");
        await GarantirSenhaAsync(db, senhas, guardadas, "ricardo.nunes@email.com", "Ricardo#2026");
    }

    private static async Task GarantirTabelasAsync(NextBusDb db)
    {
        await CriarSeNaoExistirAsync(db, "SENHA", """
            CREATE TABLE SENHA (
                id_usuario NUMBER NOT NULL,
                hash VARCHAR2(500) NOT NULL,
                CONSTRAINT SENHA_PK PRIMARY KEY (id_usuario),
                CONSTRAINT FK_SENHA_USUARIO FOREIGN KEY (id_usuario) REFERENCES USUARIO (id_usuario)
            )
            """);
        await CriarSeNaoExistirAsync(db, "IDEMPOTENCIA", """
            CREATE TABLE IDEMPOTENCIA (
                id_idempotencia NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                id_usuario NUMBER NOT NULL,
                chave VARCHAR2(80) NOT NULL,
                hash_corpo VARCHAR2(128) NOT NULL,
                id_rotina NUMBER NOT NULL,
                CONSTRAINT IDEMPOTENCIA_PK PRIMARY KEY (id_idempotencia),
                CONSTRAINT IDEMPOTENCIA_CHAVE_UK UNIQUE (id_usuario, chave)
            )
            """);
    }

    private static async Task CriarSeNaoExistirAsync(NextBusDb db, string tabela, string ddl)
    {
        var conexao = db.Database.GetDbConnection();
        var abriu = conexao.State != ConnectionState.Open;
        if (abriu)
            await conexao.OpenAsync();

        try
        {
            await using var consulta = conexao.CreateCommand();
            consulta.CommandText = "SELECT COUNT(*) FROM user_tables WHERE table_name = :nome";
            var parametro = consulta.CreateParameter();
            parametro.ParameterName = "nome";
            parametro.Value = tabela;
            consulta.Parameters.Add(parametro);
            var quantidade = Convert.ToInt32(await consulta.ExecuteScalarAsync());
            if (quantidade > 0)
                return;

            await using var criar = conexao.CreateCommand();
            criar.CommandText = ddl;
            await criar.ExecuteNonQueryAsync();
        }
        finally
        {
            if (abriu)
                await conexao.CloseAsync();
        }
    }

    private static async Task GarantirSenhaAsync(NextBusDb db, ISenhaHasher senhas, ISenhaRepository guardadas, string email, string senha)
    {
        var usuario = await db.Usuarios.SingleOrDefaultAsync(u => u.Email == email);
        if (usuario is null || await guardadas.ObterHashAsync(usuario.Id, CancellationToken.None) is not null)
            return;

        await guardadas.SalvarAsync(usuario.Id, senhas.GerarHash(senha), CancellationToken.None);
    }
}
